import { Router } from 'express';
import asyncHandler from 'express-async-handler';
import { adminOnly, protect } from '../middleware/auth.js';
import { createCategory,createCoupon,createSlide,deleteCategory,deleteCoupon,deleteSlide,listCategories,listCoupons,listSlides,updateCategory,updateCoupon,updateSlide,validateCoupon,getSettings,updateSettings,listFaqs,createFaq,updateFaq,deleteFaq,listPublicCoupons } from '../controllers/catalogController.js';
const router=Router();
router.get('/categories',asyncHandler(listCategories));
router.get('/slides',asyncHandler(listSlides));
router.get('/settings',asyncHandler(getSettings));
router.get('/faqs',asyncHandler(listFaqs));
router.get('/coupons/public',asyncHandler(listPublicCoupons));
router.post('/coupons/validate',protect,asyncHandler(validateCoupon));
router.get('/admin/categories',protect,adminOnly,asyncHandler(listCategories));
router.post('/admin/categories',protect,adminOnly,asyncHandler(createCategory));
router.put('/admin/categories/:id',protect,adminOnly,asyncHandler(updateCategory));
router.delete('/admin/categories/:id',protect,adminOnly,asyncHandler(deleteCategory));
router.get('/admin/slides',protect,adminOnly,asyncHandler(listSlides));
router.post('/admin/slides',protect,adminOnly,asyncHandler(createSlide));
router.put('/admin/slides/:id',protect,adminOnly,asyncHandler(updateSlide));
router.delete('/admin/slides/:id',protect,adminOnly,asyncHandler(deleteSlide));
router.get('/admin/coupons',protect,adminOnly,asyncHandler(listCoupons));
router.post('/admin/coupons',protect,adminOnly,asyncHandler(createCoupon));
router.put('/admin/coupons/:id',protect,adminOnly,asyncHandler(updateCoupon));
router.delete('/admin/coupons/:id',protect,adminOnly,asyncHandler(deleteCoupon));
router.get('/admin/faqs',protect,adminOnly,asyncHandler(listFaqs));
router.post('/admin/faqs',protect,adminOnly,asyncHandler(createFaq));
router.put('/admin/faqs/:id',protect,adminOnly,asyncHandler(updateFaq));
router.delete('/admin/faqs/:id',protect,adminOnly,asyncHandler(deleteFaq));
router.put('/admin/settings',protect,adminOnly,asyncHandler(updateSettings));
export default router;
